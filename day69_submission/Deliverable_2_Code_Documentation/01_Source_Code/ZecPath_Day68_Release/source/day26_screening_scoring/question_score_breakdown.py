import json
import os
from datetime import datetime, timezone


class QuestionScoreBreakdown:
    """
    Organizes individual screening question scores
    into a structured per-question breakdown.

    This component uses the scores generated by
    the ScreeningScoringEngine.
    """

    def build_question_breakdown(self, scoring_result):
        """
        Convert one screening scoring result into a
        per-question score breakdown.
        """

        scores = scoring_result.get("scores", {})

        breakdown = {
            "candidate_id": scoring_result.get("candidate_id"),
            "job_id": scoring_result.get("job_id"),
            "question_id": scoring_result.get("question_id"),
            "question": scoring_result.get("question"),
            "question_category": scoring_result.get(
                "question_category"
            ),

            "scores": {
                "clarity": scores.get("clarity", 0),
                "relevance": scores.get("relevance", 0),
                "completeness": scores.get("completeness", 0),
                "consistency": scores.get("consistency", 0)
            },

            "weighted_score": scoring_result.get(
                "weighted_score",
                0
            ),

            "normalized_score": scoring_result.get(
                "normalized_score",
                0
            ),

            "answer_status": scoring_result.get(
                "answer_status"
            ),

            "intent": scoring_result.get(
                "intent"
            ),

            "off_topic": scoring_result.get(
                "off_topic",
                False
            ),

            "explanation": {
                "strengths": scoring_result.get(
                    "explanation",
                    {}
                ).get(
                    "strengths",
                    []
                ),

                "weaknesses": scoring_result.get(
                    "explanation",
                    {}
                ).get(
                    "weaknesses",
                    []
                )
            },

            "created_at": datetime.now(
                timezone.utc
            ).isoformat()
        }

        return breakdown

    def build_candidate_breakdown(self, scoring_results):
        """
        Build a complete per-question breakdown
        for one candidate.

        scoring_results should be a list of individual
        scoring results.
        """

        question_breakdowns = []

        for scoring_result in scoring_results:

            breakdown = self.build_question_breakdown(
                scoring_result
            )

            question_breakdowns.append(
                breakdown
            )

        return {
            "candidate_id": (
                scoring_results[0].get("candidate_id")
                if scoring_results
                else None
            ),

            "job_id": (
                scoring_results[0].get("job_id")
                if scoring_results
                else None
            ),

            "total_questions": len(
                question_breakdowns
            ),

            "question_scores": question_breakdowns,

            "created_at": datetime.now(
                timezone.utc
            ).isoformat()
        }

    def save_breakdown(self, breakdown, filename):
        """
        Save the per-question breakdown as JSON
        inside the results folder.
        """

        results_dir = os.path.join(
            os.path.dirname(__file__),
            "results"
        )

        os.makedirs(
            results_dir,
            exist_ok=True
        )

        file_path = os.path.join(
            results_dir,
            filename
        )

        with open(
            file_path,
            "w",
            encoding="utf-8"
        ) as file:

            json.dump(
                breakdown,
                file,
                indent=4,
                ensure_ascii=False
            )

        return file_path


