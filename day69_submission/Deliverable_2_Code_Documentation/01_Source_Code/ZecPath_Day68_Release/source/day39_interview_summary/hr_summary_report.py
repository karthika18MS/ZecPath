import json
import os


class HRSummaryReport:

    def __init__(self, input_file):
        self.input_file = input_file
        self.summary_data = self.load_summary()

    def load_summary(self):
        """
        Loads the structured interview summary
        generated by Deliverable 1.
        """

        with open(
            self.input_file,
            "r",
            encoding="utf-8"
        ) as file:

            return json.load(file)

    def generate_report(self):

        data = self.summary_data

        report = {
            "report_title": "AI HR Interview Summary Report",

            "candidate_information": {
                "candidate_id":
                    data.get("candidate_id"),

                "job_id":
                    data.get("job_id")
            },

            "overall_performance": {
                "score":
                    data[
                        "overall_hr_performance"
                    ].get("score"),

                "level":
                    data[
                        "overall_hr_performance"
                    ].get("level"),

                "summary":
                    data[
                        "overall_hr_performance"
                    ].get("summary")
            },

            "evaluation_scores":
                data.get(
                    "evaluation_scores",
                    {}
                ),

            "strengths":
                data.get(
                    "strengths",
                    []
                ),

            "weaknesses":
                data.get(
                    "weaknesses",
                    []
                ),

            "cultural_fit_indicators":
                data.get(
                    "cultural_fit_indicators",
                    []
                ),

            "risk_flags":
                data.get(
                    "risk_flags",
                    []
                ),

            "inconsistencies":
                data.get(
                    "inconsistencies",
                    []
                )
        }

        return report

    def generate_natural_language_report(
        self,
        report
    ):
        """
        Creates a recruiter-friendly
        natural-language summary.
        """

        candidate_id = report[
            "candidate_information"
        ]["candidate_id"]

        job_id = report[
            "candidate_information"
        ]["job_id"]

        overall = report[
            "overall_performance"
        ]

        lines = []

        lines.append(
            "AI HR INTERVIEW SUMMARY REPORT"
        )

        lines.append(
            "================================"
        )

        lines.append(
            f"Candidate ID: {candidate_id}"
        )

        lines.append(
            f"Job ID: {job_id}"
        )

        lines.append("")

        lines.append(
            "OVERALL HR PERFORMANCE"
        )

        lines.append(
            f"Score: {overall['score']}/100"
        )

        lines.append(
            f"Performance Level: "
            f"{overall['level']}"
        )

        lines.append(
            f"Summary: {overall['summary']}"
        )

        lines.append("")

        lines.append(
            "EVALUATION SCORES"
        )

        for key, value in report[
            "evaluation_scores"
        ].items():

            display_name = (
                key.replace("_", " ").title()
            )

            lines.append(
                f"- {display_name}: {value}"
            )

        lines.append("")

        lines.append("STRENGTHS")

        if report["strengths"]:

            for item in report["strengths"]:
                lines.append(
                    f"- {item}"
                )

        else:
            lines.append(
                "- No major strengths identified"
            )

        lines.append("")

        lines.append("WEAKNESSES")

        if report["weaknesses"]:

            for item in report["weaknesses"]:
                lines.append(
                    f"- {item}"
                )

        else:
            lines.append(
                "- No major weaknesses identified"
            )

        lines.append("")

        lines.append(
            "CULTURAL FIT INDICATORS"
        )

        if report[
            "cultural_fit_indicators"
        ]:

            for item in report[
                "cultural_fit_indicators"
            ]:

                lines.append(
                    f"- {item}"
                )

        else:
            lines.append(
                "- No cultural fit indicators recorded"
            )

        lines.append("")

        lines.append("RISK FLAGS")

        if report["risk_flags"]:

            for item in report["risk_flags"]:
                lines.append(
                    f"- {item}"
                )

        else:
            lines.append(
                "- No major risk flags identified"
            )

        lines.append("")

        lines.append("INCONSISTENCIES")

        if report["inconsistencies"]:

            for item in report["inconsistencies"]:

                lines.append(
                    f"- {item}"
                )

        else:
            lines.append(
                "- No major inconsistencies identified"
            )

        lines.append("")

        lines.append(
            "END OF REPORT"
        )

        return "\n".join(lines)

    def save_report(
        self,
        report,
        output_file
    ):

        directory = os.path.dirname(
            output_file
        )

        if directory:
            os.makedirs(
                directory,
                exist_ok=True
            )

        with open(
            output_file,
            "w",
            encoding="utf-8"
        ) as file:

            json.dump(
                report,
                file,
                indent=4,
                ensure_ascii=False
            )


