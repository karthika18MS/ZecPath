# ============================================================
#
# Deliverable 2:
# Skill-wise Scoring Breakdown
#
# Input:
#     results/technical_scores.json
#
# Output:
#     results/skill_wise_scores.json
#
# Purpose:
#     Group technical question scores by skill domain and
#     calculate the candidate's performance for each skill.
#
# Supports:
#     - Multiple technical skills
#     - Multiple questions per skill
#     - Parameter-level averages
#     - Skill-level scores
#     - Strong / Good / Basic / Poor classification
#     - Strong-skill identification
#     - Improvement-area identification
#
# ============================================================


BASE_DIR = os.path.dirname(
    os.path.abspath(__file__)
)

RESULTS_DIR = os.path.join(
    BASE_DIR,
    "results"
)

INPUT_FILE = os.path.join(
    RESULTS_DIR,
    "technical_scores.json"
)

OUTPUT_FILE = os.path.join(
    RESULTS_DIR,
    "skill_wise_scores.json"
)


# ============================================================
# 1. LOAD TECHNICAL SCORING RESULTS
# ============================================================

def load_technical_scores() -> Dict[str, Any]:
    """
    Load the multi-question technical scoring result
    generated by Deliverable 1.
    """

    if not os.path.exists(INPUT_FILE):

        raise FileNotFoundError(
            "Technical scoring result not found:\n"
            + INPUT_FILE
        )

    with open(
        INPUT_FILE,
        "r",
        encoding="utf-8"
    ) as file:

        return json.load(file)


# ============================================================
# 2. VALIDATE INPUT
# ============================================================

def validate_input(
    data: Dict[str, Any]
) -> None:
    """
    Validate the structure generated by Deliverable 1.
    """

    required_fields = [
        "candidate_id",
        "job_id",
        "evaluation_summary",
        "question_wise_scores"
    ]

    missing_fields = [
        field
        for field in required_fields
        if field not in data
    ]

    if missing_fields:

        raise ValueError(
            "Missing required fields: "
            + ", ".join(missing_fields)
        )

    if not isinstance(
        data["question_wise_scores"],
        list
    ):

        raise ValueError(
            "question_wise_scores must be a list."
        )

    if not data["question_wise_scores"]:

        raise ValueError(
            "No technical question scores found."
        )


# ============================================================
# 3. SCORE CATEGORY
# ============================================================

def get_score_category(
    score: float
) -> str:

    if score >= 90:
        return "excellent"

    if score >= 80:
        return "strong"

    if score >= 60:
        return "good"

    if score >= 40:
        return "basic"

    return "poor"


# ============================================================
# 4. GROUP QUESTIONS BY SKILL
# ============================================================

def group_questions_by_skill(
    question_results: List[Dict[str, Any]]
) -> Dict[str, List[Dict[str, Any]]]:
    """
    Group all question results according to skill domain.
    """

    skill_groups = {}

    for result in question_results:

        skill_domain = result[
            "question"
        ][
            "skill_domain"
        ]

        if skill_domain not in skill_groups:

            skill_groups[
                skill_domain
            ] = []

        skill_groups[
            skill_domain
        ].append(result)

    return skill_groups


# ============================================================
# 5. CALCULATE PARAMETER AVERAGES
# ============================================================

def calculate_parameter_averages(
    question_results: List[Dict[str, Any]]
) -> Dict[str, float]:
    """
    Calculate average scores for the four technical
    scoring parameters within a skill.
    """

    parameters = [
        "accuracy",
        "depth",
        "logical_reasoning",
        "real_world_applicability"
    ]

    averages = {}

    for parameter in parameters:

        scores = []

        for result in question_results:

            score = result[
                "parameter_scores"
            ].get(
                parameter,
                0
            )

            scores.append(
                float(score)
            )

        if scores:

            average = (
                sum(scores)
                / len(scores)
            )

        else:

            average = 0.0

        averages[
            parameter
        ] = round(
            average,
            2
        )

    return averages


# ============================================================
# 6. CALCULATE SKILL SCORE
# ============================================================

def calculate_skill_score(
    question_results: List[Dict[str, Any]]
) -> float:
    """
    Calculate the average technical score for one skill.

    If a skill has multiple questions, their final
    normalized technical scores are averaged.
    """

    scores = []

    for result in question_results:

        score = result[
            "score_summary"
        ][
            "difficulty_normalized_score"
        ]

        scores.append(
            float(score)
        )

    if not scores:

        return 0.0

    return round(
        sum(scores) / len(scores),
        2
    )


# ============================================================
# 7. IDENTIFY STRONGEST PARAMETER
# ============================================================

def get_strongest_parameter(
    parameter_averages: Dict[str, float]
) -> Dict[str, Any]:

    strongest = max(
        parameter_averages,
        key=parameter_averages.get
    )

    return {
        "parameter": strongest,
        "score": parameter_averages[
            strongest
        ]
    }


# ============================================================
# 8. IDENTIFY WEAKEST PARAMETER
# ============================================================

def get_weakest_parameter(
    parameter_averages: Dict[str, float]
) -> Dict[str, Any]:

    weakest = min(
        parameter_averages,
        key=parameter_averages.get
    )

    return {
        "parameter": weakest,
        "score": parameter_averages[
            weakest
        ]
    }


# ============================================================
# 9. IDENTIFY SKILL STRENGTHS
# ============================================================

def identify_skill_strengths(
    skill_scores: Dict[str, float]
) -> List[str]:
    """
    Skills with score >= 80 are treated as strong skills.
    """

    strengths = []

    for skill, score in skill_scores.items():

        if score >= 80:

            strengths.append(
                skill
            )

    return strengths


# ============================================================
# 10. IDENTIFY SKILLS NEEDING IMPROVEMENT
# ============================================================

def identify_improvement_skills(
    skill_scores: Dict[str, float]
) -> List[str]:
    """
    Skills below 80 are treated as areas needing
    further improvement.
    """

    improvement_skills = []

    for skill, score in skill_scores.items():

        if score < 80:

            improvement_skills.append(
                skill
            )

    return improvement_skills


# ============================================================
# 11. BUILD ONE SKILL RESULT
# ============================================================

def build_skill_result(
    skill_domain: str,
    question_results: List[Dict[str, Any]]
) -> Dict[str, Any]:

    parameter_averages = (
        calculate_parameter_averages(
            question_results
        )
    )

    skill_score = calculate_skill_score(
        question_results
    )

    question_ids = []

    question_details = []

    for result in question_results:

        question = result[
            "question"
        ]

        question_ids.append(
            question[
                "question_id"
            ]
        )

        question_details.append({

            "question_id":
                question[
                    "question_id"
                ],

            "question_type":
                question[
                    "question_type"
                ],

            "difficulty":
                question[
                    "difficulty"
                ],

            "question_score":
                result[
                    "score_summary"
                ][
                    "difficulty_normalized_score"
                ],

            "answer_depth":
                result[
                    "answer_analysis"
                ][
                    "depth_classification"
                ]
        })

    strongest_parameter = (
        get_strongest_parameter(
            parameter_averages
        )
    )

    weakest_parameter = (
        get_weakest_parameter(
            parameter_averages
        )
    )

    return {

        "skill_domain":
            skill_domain,

        "question_count":
            len(question_results),

        "question_ids":
            question_ids,

        "parameter_averages":
            parameter_averages,

        "skill_score":
            skill_score,

        "score_category":
            get_score_category(
                skill_score
            ),

        "strongest_parameter":
            strongest_parameter,

        "weakest_parameter":
            weakest_parameter,

        "question_details":
            question_details
    }


# ============================================================
# 12. BUILD COMPLETE SKILL-WISE BREAKDOWN
# ============================================================

def build_skill_wise_breakdown(
    technical_data: Dict[str, Any]
) -> Dict[str, Any]:

    validate_input(
        technical_data
    )

    candidate_id = technical_data[
        "candidate_id"
    ]

    job_id = technical_data[
        "job_id"
    ]

    question_results = technical_data[
        "question_wise_scores"
    ]

    skill_groups = (
        group_questions_by_skill(
            question_results
        )
    )

    skill_results = []

    skill_scores = {}

    # --------------------------------------------------------
    # Build result for every skill
    # --------------------------------------------------------

    for skill_domain, results in (
        skill_groups.items()
    ):

        skill_result = build_skill_result(
            skill_domain,
            results
        )

        skill_results.append(
            skill_result
        )

        skill_scores[
            skill_domain
        ] = skill_result[
            "skill_score"
        ]

    # --------------------------------------------------------
    # Overall skill score
    #
    # Each skill contributes equally to the overall
    # skill-wise score.
    # --------------------------------------------------------

    if skill_scores:

        overall_skill_score = round(
            sum(
                skill_scores.values()
            )
            / len(skill_scores),
            2
        )

    else:

        overall_skill_score = 0.0

    # --------------------------------------------------------
    # Strong and improvement skills
    # --------------------------------------------------------

    strong_skills = (
        identify_skill_strengths(
            skill_scores
        )
    )

    improvement_skills = (
        identify_improvement_skills(
            skill_scores
        )
    )

    return {

        "engine":
            "ZecPath Day 47 Skill-wise Scoring Breakdown",

        "data_type":
            technical_data.get(
                "data_type",
                "DEMO_SAMPLE_DATA"
            ),

        "candidate_id":
            candidate_id,

        "job_id":
            job_id,

        "skill_wise_scoring":
            skill_results,

        "skill_summary": {

            "total_skills":
                len(skill_results),

            "skills_evaluated":
                list(
                    skill_scores.keys()
                ),

            "strong_skills":
                strong_skills,

            "skills_needing_improvement":
                improvement_skills
        },

        "overall_technical_skill_score":
            overall_skill_score,

        "overall_score_category":
            get_score_category(
                overall_skill_score
            ),

        "scoring_method":
            (
                "Each skill score is calculated as "
                "the average of the normalized technical "
                "scores of all questions belonging to "
                "that skill. The overall technical skill "
                "score is the average of the skill scores."
            ),

        "overall_status":
            "SUCCESS"
    }


# ============================================================
# 13. SAVE RESULT
# ============================================================

def save_result(
    result: Dict[str, Any]
) -> str:

    os.makedirs(
        RESULTS_DIR,
        exist_ok=True
    )

    with open(
        OUTPUT_FILE,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            result,
            file,
            indent=4,
            ensure_ascii=False
        )

    return OUTPUT_FILE


